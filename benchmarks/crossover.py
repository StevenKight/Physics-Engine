"""Finds the body count where CUDA gravity starts beating Fortran.

Reads the newest CSV in benchmarks/results/ and writes benchmarks/CROSSOVER.md.

Usage: python3 benchmarks/crossover.py
"""

import csv
import math
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent


def read_threshold():
    """Reads the default GRAVITY_GPU_THRESHOLD from gravity.c."""
    source = (HERE.parent / "src/logic/forces/gravity.c").read_text()
    match = re.search(r"#define\s+GRAVITY_GPU_THRESHOLD\s+\(?(\d+)", source)
    if not match:
        raise SystemExit("Could not find GRAVITY_GPU_THRESHOLD in gravity.c")
    return int(match.group(1))


CURRENT_THRESHOLD = read_threshold()


def latest_csv():
    files = sorted((HERE / "results").glob("bench_*.csv"))
    if not files:
        raise SystemExit("No results found. Run ./benchmarks/run.sh first.")
    return files[-1]


def load(path):
    """Returns {(scenario, backend, threads): {n: row}}, timed rows only."""
    series = {}
    with open(path) as f:
        for row in csv.DictReader(f):
            if row["note"]:
                continue
            for key in ("median_ms", "min_ms", "max_ms"):
                row[key] = float(row[key])
            key = (row["scenario"], row["backend"], int(row["threads"]))
            series.setdefault(key, {})[int(row["n"])] = row
    return series


def find_crossover(fortran, cuda):
    """Smallest N where CUDA's median is below Fortran's for that N and every
    larger N. Returns (n_before, n_after, estimate) or None if CUDA never wins.
    The estimate interpolates log(speedup) against log(N) across the bracket."""
    ns = sorted(set(fortran) & set(cuda))
    speedup = {n: fortran[n]["median_ms"] / cuda[n]["median_ms"] for n in ns}

    after = None
    for n in reversed(ns):
        if speedup[n] <= 1.0:
            break
        after = n
    if after is None:
        return None

    i = ns.index(after)
    if i == 0:
        return None, after, None

    before = ns[i - 1]
    s0, s1 = math.log(speedup[before]), math.log(speedup[after])
    t = -s0 / (s1 - s0)
    estimate = math.exp(math.log(before) + t * (math.log(after) - math.log(before)))
    return before, after, estimate


def verdict(before, after):
    # The router sends N > CURRENT_THRESHOLD to CUDA.
    if before is not None and before > CURRENT_THRESHOLD:
        return "too low: CUDA is still slower than Fortran just above it"
    if after <= CURRENT_THRESHOLD:
        return "too high: CUDA already wins at or below it"
    return "about right: the crossover falls between the measured points around it"


def main():
    path = latest_csv()
    series = load(path)
    fortran = series[("gravity", "fortran", 1)]
    cuda = series[("gravity", "cuda", 1)]
    router = series.get(("gravity", "router", 1), {})

    lines = [
        "# Fortran vs CUDA Crossover",
        "",
        f"Generated by `benchmarks/crossover.py` from `results/{path.name}`.",
        "Hardware and toolchain: see [ENVIRONMENT.md](ENVIRONMENT.md).",
        "",
        "Gravity only (`newtonian_gravity`), one call per run, median of 10 runs "
        "with min to max in brackets. Speedup is Fortran median / CUDA median.",
        "",
        "| N | Fortran (ms) | CUDA (ms) | Router (ms) | Speedup |",
        "|---|---|---|---|---|",
    ]

    for n in sorted(set(fortran) & set(cuda)):
        f, c = fortran[n], cuda[n]
        r = f"{router[n]['median_ms']:.3f}" if n in router else "-"
        lines.append(
            f"| {n} | {f['median_ms']:.3f} [{f['min_ms']:.3f}-{f['max_ms']:.3f}] "
            f"| {c['median_ms']:.3f} [{c['min_ms']:.3f}-{c['max_ms']:.3f}] "
            f"| {r} | {f['median_ms'] / c['median_ms']:.3g}x |"
        )

    lines.append("")
    result = find_crossover(fortran, cuda)
    if result is None:
        lines.append("CUDA never beats Fortran in this data.")
    else:
        before, after, estimate = result
        f, c = fortran[after], cuda[after]
        overlap = c["max_ms"] >= f["min_ms"]
        lines += [
            "## Result",
            "",
            f"- CUDA is faster at N = {after} and every larger N measured.",
        ]
        if before is not None:
            lines.append(
                f"- The crossover lies between N = {before} and N = {after}; "
                f"interpolating the speedup in log-log gives N ≈ {estimate:.0f}."
            )
        lines += [
            f"- Spread at N = {after}: CUDA {c['min_ms']:.3f}-{c['max_ms']:.3f} ms, "
            f"Fortran {f['min_ms']:.3f}-{f['max_ms']:.3f} ms "
            f"({'ranges overlap' if overlap else 'no overlap'}).",
            f"- The current threshold of {CURRENT_THRESHOLD} is "
            f"{verdict(before, after)}.",
        ]
        best = max(
            (fortran[n]["median_ms"] / cuda[n]["median_ms"], n)
            for n in set(fortran) & set(cuda)
        )
        lines.append(f"- Best measured speedup: {best[0]:.2f}x at N = {best[1]}.")

    out = HERE / "CROSSOVER.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"Wrote {out.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main()
