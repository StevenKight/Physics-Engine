#!/usr/bin/env bash
# Records the machine and toolchain used for benchmarks into ENVIRONMENT.md.
# Run from anywhere: ./benchmarks/record_env.sh

cd "$(dirname "$0")" || exit 1
out=ENVIRONMENT.md
cache=../build/bench/CMakeCache.txt

section() {
    echo
    echo "## $1"
    echo
    echo '```'
    shift
    "$@" 2>&1 || echo "(not available)"
    echo '```'
}

# Prints the compiler CMake cached for language $1 in build/bench, or $2 if
# build/bench hasn't been configured yet.
compiler() {
    path=$(grep -m1 "^CMAKE_$1_COMPILER:" "$cache" 2>/dev/null | cut -d= -f2-)
    echo "${path:-$2}"
}

{
    echo "# Benchmark Environment"
    echo
    echo "Generated by \`record_env.sh\` on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
    echo
    echo "Benchmarks are built in \`build/bench\` with \`CMAKE_BUILD_TYPE=Release\`"
    echo "and the compilers CMake picked for it, listed below."
    section "GPU" nvidia-smi --query-gpu=name,driver_version,memory.total,compute_cap --format=csv
    section "CUDA" "$(compiler CUDA nvcc)" --version
    section "C compiler" "$(compiler C gcc)" --version
    section "C++ compiler" "$(compiler CXX g++)" --version
    section "Fortran compiler" "$(compiler Fortran gfortran)" --version
    section "CMake" cmake --version
    section "CPU" lscpu
    section "OS" uname -srmo
} > "$out"

echo "Wrote benchmarks/$out"
